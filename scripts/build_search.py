"""Refresh the small browse catalog and the on-demand full-text search data."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PAGE = ROOT / "search.html"
CORPUS = ROOT / "assets" / "search-text.js"


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def build(check):
    entries = json.loads((ROOT / "search-index.json").read_text(encoding="utf-8"))
    fields = ("title", "summary", "url", "thumbnail", "updated", "group", "kind", "tags")
    catalog = [{field: item[field] for field in fields} for item in entries]
    # Older exports include research aliases and summaries beyond the public card copy.
    corpus = {item["url"]: [item["search"], item["summary_norm"]] for item in entries}
    data = "/* Generated by scripts/build_search.py. */\nconst archiveSearchText = " + compact(corpus) + ";\n"
    version = hashlib.sha256(data.encode()).hexdigest()[:10]
    inline = compact(catalog).replace("<", "\\u003c")
    tag = f'<script id="search-data" type="application/json" data-text-src="assets/search-text.js?v={version}">{inline}</script>'
    page = PAGE.read_text(encoding="utf-8")
    updated, count = re.subn(r'<script id="search-data"[^>]*>.*?</script>', lambda _: tag, page, flags=re.S)
    if count != 1:
        raise SystemExit("Expected one search catalog in search.html")
    for path, content in ((CORPUS, data), (PAGE, updated)):
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if check:
            raise SystemExit(f"Run python scripts/build_search.py to refresh {path.name}")
        path.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
